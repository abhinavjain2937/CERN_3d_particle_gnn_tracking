"""Turn metrics.json into Markdown (README) and LaTeX macros (resume)."""
from __future__ import annotations


def _pm(mean: float, std: float, nd: int = 4) -> str:
    return f"{mean:.{nd}f} ± {std:.{nd}f}"


def metrics_table_md(m: dict) -> str:
    d = m["dataset"]
    lines = [
        f"Split: **{d['n_train']} train / {d['n_val']} validation / {d['n_test']} test** events "
        f"(disjoint, chosen by sorted file name). Mean graph size: {d['mean_nodes']:,.0f} hits, "
        f"{d['mean_edges']:,.0f} candidate edges per event; {100 * d['mean_positive_rate']:.1f}% of edges are true same-particle links.",
        "",
        "| Model | Threshold (chosen on validation) | Val ROC-AUC | Test ROC-AUC | Test precision | Test recall | Test F1 | Train ROC-AUC (in-sample) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, r in m["models"].items():
        tag = f"**{name}** (selected)" if name == m["final_model"] else name
        t, s = r["test_mean"], r["test_std"]
        lines.append(
            f"| {tag} | {r['threshold']:.2f} | {r['val_roc_auc']:.4f} | {_pm(t['roc_auc'], s['roc_auc'])} | "
            f"{_pm(t['precision'], s['precision'])} | {_pm(t['recall'], s['recall'])} | "
            f"{_pm(t['f1'], s['f1'])} | {r['train_mean']['roc_auc']:.4f} |")
    lines += ["", "Test numbers are mean ± std over the test events; the model and threshold were chosen on validation events only."]
    return "\n".join(lines)


def _tex_int(n: float, step: int = 100) -> str:
    return f"{int(round(n / step) * step):,}".replace(",", "{,}")


def resume_macros(m: dict) -> str:
    """LaTeX \\newcommand lines used by the resume (\\input{trackml_metrics.tex})."""
    d = m["dataset"]
    best = m["models"][m["final_model"]]
    t, s = best["test_mean"], best["test_std"]
    macros = {
        "trkNevents": str(d["n_train"] + d["n_val"] + d["n_test"]),
        "trkNtrain": str(d["n_train"]),
        "trkNval": str(d["n_val"]),
        "trkNtest": str(d["n_test"]),
        "trkNodes": _tex_int(d["mean_nodes"]),
        "trkEdges": _tex_int(d["mean_edges"]),
        "trkPosPct": f"{100 * d['mean_positive_rate']:.1f}",
        "trkAUC": f"{t['roc_auc']:.3f}",
        "trkAUCstd": f"{s['roc_auc']:.3f}",
        "trkPrec": f"{t['precision']:.3f}",
        "trkRec": f"{t['recall']:.3f}",
        "trkFone": f"{t['f1']:.3f}",
        "trkThr": f"{best['threshold']:.2f}",
        "trkModel": m["final_model"].replace("_", "\\_"),
    }
    head = "% Auto-generated by scripts/export_resume_macros.py from metrics.json. Do not edit by hand.\n"
    return head + "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()) + "\n"
